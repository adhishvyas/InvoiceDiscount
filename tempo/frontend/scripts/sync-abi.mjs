// Regenerates src/abi/*.ts (and the mpp-server's copy) from the Foundry build: `pnpm sync-abi` (needs forge on PATH or in ~/.foundry/bin).
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contracts = resolve(here, '../../contracts');
const outs = [resolve(here, '../src/abi'), resolve(here, '../../mpp-server/src/abi')];
const env = { ...process.env, PATH: `${join(homedir(), '.foundry/bin')}:${process.env.PATH}` };

for (const out of outs) mkdirSync(out, { recursive: true });
for (const [name, constName] of [
  ['InvoiceEscrow', 'invoiceEscrowAbi'],
  ['InvoiceFactory', 'invoiceFactoryAbi'],
]) {
  const abi = execFileSync('forge', ['inspect', name, 'abi', '--json'], { cwd: contracts, env }).toString();
  const body = `// Generated by scripts/sync-abi.mjs from \`forge inspect ${name} abi\`. Do not edit.\nexport const ${constName} = ${JSON.stringify(JSON.parse(abi), null, 2)} as const;\n`;
  for (const out of outs) {
    writeFileSync(join(out, `${name}.ts`), body);
    console.log(`wrote ${join(out, `${name}.ts`)}`);
  }
}
